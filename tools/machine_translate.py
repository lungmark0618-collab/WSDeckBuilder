def translate_line(line, names, traits):
    """翻譯一行；殘留假名則回傳 None（保留日文）。"""
    # 保護「」內卡名：已知譯名替換、未知保留原文（卡名保留日文不算失敗）
    protected = {}

    # 只保護內文、保留《》「」外框，讓「》のキャラ」等規則能運作
    def protect_name(match):
        inner = match.group(1)
        token = f"⟪{len(protected)}⟫"
        protected[token] = names.get(inner, inner)
        return "「" + token + "」"

    def protect_trait(match):
        inner = match.group(1)
        token = f"⟪{len(protected)}⟫"
        protected[token] = traits.get(inner, inner)
        return "《" + token + "》"

    text = re.sub(r"「([^」]+)」", protect_name, line)
    text = re.sub(r"《([^》]+)》", protect_trait, text)

    for pattern, repl in RULES:
        text = pattern.sub(repl, text)
    for pattern, repl in POST_RULES:
        text = pattern.sub(repl, text)

    if KANA.search(text):
        return None                      # 沒翻乾淨，整行退回日文
    for token, original in protected.items():
        text = text.replace(token, original)
    return text


def translate_name(name, chars, words, names):
    if name in names:
        return names[name]
    text = name
    # 角色譯名換成私有區的單一字元佔位，等其他規則跑完再還原。
    # 否則後續詞彙規則會咬進譯名裡——「夢→夢想」就曾把「七詩夢命」
    # 變成「七詩夢想命」。佔位字元不在任何規則的比對範圍內。
    holds = []
    for jp, zh in sorted(chars.items(), key=lambda kv: -len(kv[0])):
        if jp in text:
            text = text.replace(jp, chr(0xE000 + len(holds)))
            holds.append(zh)
    merged = dict(JP_WORDS)
    merged.update(words)
    if merged:
        pat = re.compile("|".join(re.escape(k) for k in
                                  sorted(merged, key=len, reverse=True)))
        text = pat.sub(lambda m: merged[m.group(0)], text)   # 單次掃描，不連鎖
    text = re.sub(r"([^\s])の([^\s])", r"\1的\2", text)   # 卡名的「の」→「的」
    text = text.replace("たち", "們").replace("ちゃん", "").replace("さん", "")
    if KANA.search(text):
        return None                      # 仍有假名 → 整個卡名保留日文
    text = text.translate(SHINJITAI)     # 新字體轉正體
    for i, zh in enumerate(holds):
        text = text.replace(chr(0xE000 + i), zh)
    return text


def translate_card_text(text, names, traits):
    """逐行翻譯。回傳 (zh_text, translated_lines, total_lines)。"""
    lines = text.split("\n")
    out, done = [], 0
    for line in lines:
        if not line.strip():
            out.append(line)
            continue
        zh = translate_line(line, names, traits)
        if zh is not None:
            out.append(zh)
            done += 1
        else:
            out.append(line)
    return "\n".join(out), done, len([l for l in lines if l.strip()])


def bench():
    """用 BRD 人工譯文評測引擎。"""
    sys.path.insert(0, HERE)
    from translate import load_translations
    _, names, traits, chars, words, _by = load_shared()
    hand_names, hand_traits, texts_by_id = load_translations()
    raw = json.load(open(os.path.join(HERE, "raw_cards.json"), encoding="utf-8"))
    cards = {c["id"]: c for c in raw["cards"]}

    line_total = line_done = line_exact = 0
    misses = []
    for cid, hand_zh in texts_by_id.items():
        card = cards.get(cid)
        if not card or not card["text_jp"]:
            continue
        jp_lines = card["text_jp"].split("\n")
        zh_lines = hand_zh.split("\n")
        for i, jp in enumerate(jp_lines):
            if not jp.strip():
                continue
            line_total += 1
            got = translate_line(jp, hand_names, hand_traits)
            if got is None:
                misses.append(("未翻完", cid, jp[:50]))
                continue
            line_done += 1
            if i < len(zh_lines) and got == zh_lines[i]:
                line_exact += 1
            else:
                expected = zh_lines[i] if i < len(zh_lines) else ""
                misses.append(("不一致", cid, f"{got[:60]} ≠ {expected[:60]}"))
    print(f"行數 {line_total}，翻完 {line_done}（{line_done/line_total:.0%}），"
          f"與人工完全一致 {line_exact}（{line_exact/line_total:.0%}）")
    for kind, cid, info in misses[:25]:
        print(f"  [{kind}] {cid}: {info}")
    print(f"（共 {len(misses)} 筆差異）")


def run_set(raw_path, key):
    _, names, traits, chars, words, by_set = load_shared()
    chars = {**chars, **by_set.get(key, {})}   # 作品覆寫優先
    raw = json.load(open(raw_path, encoding="utf-8"))
    out = {"names": {}, "traits": {}}
    cards_done = names_done = 0
    seen_text = {}
    for card in raw["cards"]:
        zh_name = translate_name(card["name_jp"], chars, words, names)
        if zh_name and zh_name != card["name_jp"]:
            out["names"][card["name_jp"]] = zh_name
            names_done += 1
        jp = card["text_jp"]
        if not jp:
            continue
        if jp in seen_text:
            continue
        zh, done, total = translate_card_text(jp, names, traits)
        seen_text[jp] = True
        if done == total and total > 0:   # 全部行都翻完才收錄
            out[card["id"]] = zh
            cards_done += 1
    for trait in {t for c in raw["cards"] for t in c["traits_jp"]}:
        if trait in traits:
            out["traits"][trait] = traits[trait]
    dest = os.path.join(HERE, "translations", f"auto_{key}.json")
    with open(dest, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
    unique = len(seen_text)
    print(f"{key}: 唯一文字 {unique}，全文翻完 {cards_done}"
          f"（{cards_done/max(unique,1):.0%}），卡名 {names_done} → {dest}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bench", action="store_true")
    ap.add_argument("--set", dest="raw_path")
    ap.add_argument("--key")
    args = ap.parse_args()
    if args.bench:
        bench()
    elif args.raw_path and args.key:
        run_set(args.raw_path, args.key)
    else:
        ap.print_help()


if __name__ == "__main__":
    main()
